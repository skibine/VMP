// region i18n [DOMAIN(7): UI; CONCEPT(7): i18n; TECH(6): svelte/store]
// Tiny dependency-free i18n. `locale` store (en|ru) persisted to localStorage; `t` is a derived
// store whose value is a translate(key, params?) function — use as $t('key') in components so
// every usage re-renders on locale change. Default = 'en' (per product decision); RU via toggle.
// Policy: translate all user-facing chrome; KEEP technical field identifiers (api_url, bot_token,
// ssh_user, model, ...), brand names (VM Pulse / VMPilot) and VM-sourced data untranslated.
// STRUCTURE: ▶ ┌locale┐ → derived → 〈dict[locale][key] ?? key〉 → ⊕ {param} inject → ⎋ string
import { writable, derived } from 'svelte/store'
import { api } from './api.js'

const LOCALE_KEY = 'vmpulse_locale'

export const locale = writable(localStorage.getItem(LOCALE_KEY) || 'en')
locale.subscribe((v) => localStorage.setItem(LOCALE_KEY, v))

export function setLocale(v) {
  locale.set(v)
  // Persist to the server so alert messages are sent in the operator's chosen language.
  api.setLocale(v).catch(() => {})
}

// On login, adopt the locale stored server-side (keeps server-delivered alerts in sync with the UI).
export async function initLocaleFromServer() {
  try {
    const r = await api.getLocale()
    if (r.locale === 'ru' || r.locale === 'en') locale.set(r.locale)
  } catch (_) {}
}

